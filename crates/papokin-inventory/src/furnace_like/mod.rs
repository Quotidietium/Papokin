//! 类熔炉容器模块。
//!
//! 本模块处理类熔炉方块的屏幕处理器：
//! - 熔炉
//! - 烟熏炉
//! - 高炉
//!
//! 这些容器共用相同的槽位布局和行为：
//! - 槽位 0：输入（待熔炼/烹饪的物品）
//! - 槽位 1：燃料（煤炭、木炭等）
//! - 槽位 2：输出（熔炼/烹饪产物）
//!
//! # Properties
//!
/// 类熔炉容器会跟踪四个属性：
/// - 属性 0：火焰图标（剩余燃料）
/// - 属性 1：最大燃料燃烧时间
/// - 属性 2：进度箭头（熔炼进度）
/// - 属性 3：最大进度（通常为 200 刻）
pub mod furnace_like_screen_handler;
pub mod furnace_like_slot;
